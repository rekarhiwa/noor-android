package com.dya.noor.module;

public class QuranSuraLisMP3Item {

    private final int id;
    private final String name;
    private final String link;

    public QuranSuraLisMP3Item(int id, String name, String link) {
        this.id = id;
        this.name = name;
        this.link = link;
    }




    public int getId() {
        return id;
    }



    public String getName() {
        return name;
    }

    public String getLink() {
        return link;
    }

}
